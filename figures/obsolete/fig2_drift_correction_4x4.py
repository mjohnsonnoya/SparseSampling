label_panel(ax_m, 'm')

# (n) FFT of corrected A  [old panel (l)]
ax_n = fig.add_subplot(gs[3, 3])
ax_n.plot(freqs, fft_perfect, color=ref_color, alpha=0.6, lw=0.8, label='Ideal')
ax_n.plot(freqs, fft_corrected, color=corr_color, lw=0.8, label='Corrected')
ax_n.set_xlim(*xlim_fft)
ax_n.set_ylabel('|FFT|')
