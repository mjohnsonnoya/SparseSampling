"""
Fig. 2 (assembled): Lawler-Fujita drift correction in 1D, 4x4 layout.

SUPERSEDED 2026-09-12 by fig2_drift_correction_condensed.py (3x4, eight
panels) after cold reads flagged redundant panels. Kept for reference.

Supersedes the 3x4 `fig_drift_correction_1d.py` by folding in the two
off-grid-resampling panels drafted for the June 2026 meeting action item:

  figures/fig2_nudft_resampling_panel.py  -> panel (k)
  figures/fig2_inverse_fft_panel.py       -> panel (l)

Everything is rendered in ONE matplotlib figure so panel fonts, line widths
and marker sizes cannot drift between the parent panels and the new ones, and
so the whole figure is regenerated by a single command.

Layout (4 panel rows x 4 columns; (k) and (l) each span two columns and are
internally a stacked pair of axes):

  Row 1  (a) perfect lattice      (b) drift field u(r)   (c) distorted signal   (d) FFT broadening
  Row 2  (e) A.cos(kr)            (f) A.sin(kr)          (g) LPF -> X(r)        (h) LPF -> Y(r)
  Row 3  (i) extracted theta(r)   (j) recovered u(r)     (k) kernel reassigned to x~_n  [spans 2]
  Row 4  (l) back on uniform grid [spans 2]              (m) corrected signal   (n) FFT sharpened

Panel-letter remap from the old 3x4 figure: a-j unchanged, old (k) -> (m),
old (l) -> (n); (k) and (l) are new.

Signal generation is copied verbatim from fig_drift_correction_1d.py, and the
sample positions in (k)/(l) are the ones locked in the standalone panel
scripts, so no numbers change under assembly.

Usage:
    .venv/bin/python figures/fig2_drift_correction_4x4.py
"""
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.patches import ConnectionPatch
from scipy.ndimage import gaussian_filter1d
import warnings
warnings.filterwarnings('ignore')

try:
    plt.rcParams['font.family'] = 'Arial'
except Exception:
    plt.rcParams['font.family'] = 'sans-serif'
plt.rcParams['font.size'] = 7
plt.rcParams['axes.labelsize'] = 7
plt.rcParams['axes.titlesize'] = 8
plt.rcParams['xtick.labelsize'] = 6
plt.rcParams['ytick.labelsize'] = 6
plt.rcParams['xtick.major.pad'] = 2
plt.rcParams['ytick.major.pad'] = 2
plt.rcParams['axes.labelpad'] = 2

# ═══════════════════════════════════════════════════════════════
# Signal generation (verbatim from fig_drift_correction_1d.py)
# ═══════════════════════════════════════════════════════════════
L = 14.0
N = 1000
d = 2.0
k = 2 * np.pi / d

x = np.linspace(0, L, N, endpoint=False)
dx = x[1] - x[0]
A_perfect = np.cos(k * x)

# Drift field: logarithmic (piezo relaxation model)
theta_fn = lambda r: np.log(r + 1)
u_fn = lambda r: theta_fn(r) / k
A_distorted = np.cos(k * x + theta_fn(x))

# Lock-in demodulation
ref_cos = np.cos(k * x)
ref_sin = np.sin(k * x)
prod_cos = A_distorted * ref_cos
prod_sin = A_distorted * ref_sin

# Low-pass filter
sigma_pixels = 80
X_r = gaussian_filter1d(prod_cos, sigma=sigma_pixels)
Y_r = gaussian_filter1d(prod_sin, sigma=sigma_pixels)

# Phase extraction
theta_extracted = np.unwrap(np.arctan2(-Y_r, X_r))
u_extracted = theta_extracted / k

# Correction
r_tilde = x + u_extracted
A_corrected = np.interp(x, r_tilde, A_distorted)

# FFTs
# Angular wavevector (rad/nm), so the lattice peak sits at q = k = pi nm^-1
# and q means the same thing on the FFT axes as in the cos(qr) of panel (k).
# (Was cycles/nm, peak at 0.5, which a cold read flagged as a second 'q'.)
freqs = 2 * np.pi * np.fft.fftshift(np.fft.fftfreq(N, d=dx))
fft_perfect = np.abs(np.fft.fftshift(np.fft.fft(A_perfect)))
fft_distorted = np.abs(np.fft.fftshift(np.fft.fft(A_distorted)))
fft_corrected = np.abs(np.fft.fftshift(np.fft.fft(A_corrected)))

# Atom positions
atoms_perfect = np.arange(0, 11, d)
# Where each ideal site a appears in the recording: the r with r + u(r) = a
# (exact inverse of the r~ = r + u(r) map, not the first-order a - u(a)).
atoms_distorted = np.interp(atoms_perfect, x + u_fn(x), x)

# ═══════════════════════════════════════════════════════════════
# Sample positions for the resampling panels (k), (l)
# Symbols (2026-09-07, aligned with paper/main.tex Eq. BPDN): positions are
# r_n / r~_n in labels and caption (r = position, as in the caption of
# panels a-j; x is the Fourier-coefficient vector in the manuscript), the
# coefficients are x_q / x~_q, and the inverse transform is F^{-1}. The
# array names below (x_n, x_corr) predate that and are left as-is.
# Locked in figures/fig2_nudft_resampling_panel.py: spacing 1.25 nm avoids
# multiples of the period d (else every sample sits at the same phase of the
# mode); range capped at 8.0 so the legends never cover a marker.
# ═══════════════════════════════════════════════════════════════
x_n = np.arange(0.5, 8.1, 1.25)
x_corr = x_n + u_fn(x_n)          # Fig. 2 convention: x~_n = x_n + u(x_n)

x_dense = np.linspace(0, 11, 1200)
mode_dense = np.cos(k * x_dense)

y_kernel_grid = np.cos(k * x_n)      # (k) top: mode value at nominal x_n
y_kernel_corr = np.cos(k * x_corr)   # (k) bottom: mode value at corrected x~_n
y_reg = np.cos(k * x_corr)           # (l) top: measured y_n placed at x~_n
y_out = np.cos(k * x_n)              # (l) bottom: recomputed on-grid values y~_n

# Colour roles (2026-09-07): the original red/green pair for distorted vs
# corrected fails the lab's no-red-green rule (Hoffman figure conventions).
# Replaced with the Okabe-Ito vermillion/blue pair, which stays distinct
# under protanopia and deuteranopia, and the ideal-lattice reference moved
# to neutral grey. Row 2 (lock-in channels) is also vermillion: every curve
# there is computed from the uncorrected signal, and colour encodes only
# before/after correction in this figure (channel is named per panel).
uncorr_color = '#D55E00'   # Okabe-Ito vermillion: "distorted / measured"
corr_color = '#0072B2'     # Okabe-Ito blue:       "corrected"
ref_color = '0.45'         # neutral grey:         "perfect / ideal reference"
mode_color = '0.15'
link_color = '0.55'

# ═══════════════════════════════════════════════════════════════
# Figure layout
# ═══════════════════════════════════════════════════════════════
# Explicit geometry rather than tight/constrained layout.
#
# Observed on this figure (matplotlib 3.11.1): with constrained layout, via
# either `constrained_layout=True` + the deprecated
# Figure.set_constrained_layout_pads() or `layout='constrained'` +
# fig.get_layout_engine().set(), each row's panel titles landed on top of the
# previous row's tick labels, and the two variants rendered at the same output
# size. Explicit margins below produce correct spacing.
#
# NOT verified: why the engine misbehaves here. The plausible cause is the
# spanning cells that contain their own nested gridspec, but no diagnostic was
# run, and the blanket warnings.filterwarnings('ignore') above would hide any
# "not applied" message matplotlib emits. If you want the real answer, rerun
# both variants with warnings enabled and compare hashes; do not treat the
# nested-gridspec explanation as established.
#
# Fixed margins are also version-independent, which matters because this repo
# runs matplotlib 3.10.8 locally.
fig = plt.figure(figsize=(6.67, 7.1))
gs = fig.add_gridspec(
    4, 4,
    left=0.072, right=0.995, bottom=0.052, top=0.955,
    hspace=0.42, wspace=0.34,
)

xlim_signal = (-0.5, 11)
xlim_fft = (-4 * np.pi, 4 * np.pi)   # same span as the old (-2, 2) cycles/nm
XLABEL_POS = r'Position $r$ (nm)'
XLABEL_FREQ = r'Frequency $q$ (nm$^{-1}$)'


def label_panel(ax, letter, x=0.03, y=0.95):
    ax.text(x, y, f'({letter})', transform=ax.transAxes,
            fontsize=8, fontweight='bold', va='top', ha='left',
            bbox=dict(facecolor='white', edgecolor='none', alpha=0.7, pad=1))


def stacked_pair(subspec, curve_color=mode_color):
    """Two vertically stacked, x-shared axes inside one grid cell.

    Used for (k) and (l), which each show the same abscissa twice (one frame
    per assignment of the samples). hspace matches the 0.38 locked in the
    standalone panel scripts.
    """
    inner = subspec.subgridspec(2, 1, hspace=0.38)
    ax_top = fig.add_subplot(inner[0])
    ax_bot = fig.add_subplot(inner[1], sharex=ax_top)
    ax_top.tick_params(labelbottom=False)
    for ax in (ax_top, ax_bot):
        ax.plot(x_dense, mode_dense, color=curve_color, lw=0.8, zorder=1)
        ax.set_xlim(*xlim_signal)
        ax.set_ylim(-1.3, 1.3)
        ax.set_yticks([-1, 0, 1])
    return ax_top, ax_bot


# ── Row 1: Setup + diagnostic FFT ────────────────────────────

# (a) Perfect lattice
ax_a = fig.add_subplot(gs[0, 0])
ax_a.plot(x, A_perfect, color=ref_color, lw=0.8)
# Lattice-site dots sit ON the peaks (2026-09-07 cold-read fix: on the zero
# line they read as unexplained tick marks).
ax_a.plot(atoms_perfect, np.cos(k * atoms_perfect), 'o', color=ref_color,
          ms=3.5, mec='white', mew=0.4, zorder=5, label='Lattice sites')
ax_a.legend(fontsize=5, loc='lower right', handlelength=1.0)
ax_a.set_xlim(*xlim_signal)
