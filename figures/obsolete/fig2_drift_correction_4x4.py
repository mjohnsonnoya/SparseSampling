ax_a.set_ylim(-2, 2)
ax_a.set_ylabel('Height')
ax_a.set_title(r"Ideal lattice $\cos(kr)$")
label_panel(ax_a, 'a')

# (b) Drift field u(r)
ax_b = fig.add_subplot(gs[0, 1])
# Same grey as every other 'true / ideal' curve (a, c, i, j, m); was black.
ax_b.plot(x, u_fn(x), color=ref_color, lw=1.2)
ax_b.set_xlim(*xlim_signal)
ax_b.set_xlabel(XLABEL_POS)
ax_b.set_ylabel('$u(r)$ (nm)')
ax_b.set_title(r"Drift $u(r)=\ln(r+1)/k$")
label_panel(ax_b, 'b')

# (c) Distorted signal overlaid
ax_c = fig.add_subplot(gs[0, 2])
ax_c.plot(x, A_perfect, color=ref_color, alpha=0.5, lw=0.6, label='Ideal lattice')
ax_c.plot(x, A_distorted, color=uncorr_color, lw=0.6, label='Distorted (measured)')
ax_c.plot(atoms_perfect, np.cos(k * atoms_perfect), 'o', color=ref_color,
          alpha=0.6, ms=3, mec='white', mew=0.4, zorder=4)
ax_c.plot(atoms_distorted, np.interp(atoms_distorted, x, A_distorted), 'o',
          color=uncorr_color, ms=3, mec='white', mew=0.4, zorder=5)
# Per-atom displacement arrows removed (2026-09-07): at this panel size the
# shafts were sub-point, leaving unexplained arrowheads on the curve peaks,
# and the displacement is already shown by the curve offset and the dot pairs.
ax_c.set_xlim(*xlim_signal)
ax_c.set_xlabel(XLABEL_POS)
ax_c.set_ylim(-2, 2)
# Legend handles show line + dot so the site markers are explained by the
# two existing entries rather than two extra ones.
ax_c.legend([Line2D([], [], color=ref_color, alpha=0.6, lw=0.6, marker='o', ms=3, mec='white', mew=0.4),
             Line2D([], [], color=uncorr_color, lw=0.6, marker='o', ms=3, mec='white', mew=0.4)],
            ['Ideal lattice', 'Distorted (measured)'],
            fontsize=5, loc='lower right', handlelength=1.6)
ax_c.set_title(r"Measured $A(r)=\cos[k(r+u(r))]$")
label_panel(ax_c, 'c')

# (d) FFT: perfect vs distorted
ax_d = fig.add_subplot(gs[0, 3])
ax_d.plot(freqs, fft_perfect, color=ref_color, lw=0.8, alpha=0.6, label='Ideal')
ax_d.plot(freqs, fft_distorted, color=uncorr_color, lw=0.8, label='Distorted')
ax_d.set_xlim(*xlim_fft)
ax_d.set_xlabel(XLABEL_FREQ)
ax_d.set_ylabel('|FFT|')
ax_d.legend(fontsize=5)
ax_d.set_title("FFT: peak broadening")
label_panel(ax_d, 'd')


# ── Row 2: Lock-in demodulation pipeline ─────────────────────

# (e) cos lock-in product (raw)
ax_e = fig.add_subplot(gs[1, 0])
ax_e.plot(x, prod_cos, color=uncorr_color, lw=0.5, alpha=0.6, label=r'$A(r) \cdot \cos(kr)$')
ax_e.plot(x, 0.5 * np.cos(theta_fn(x)), 'k--', lw=1, alpha=0.7,
          label=r'$\frac{1}{2}\cos(\theta)$ (slow)')
ax_e.set_xlim(*xlim_signal)
ax_e.set_xlabel(XLABEL_POS)
ax_e.set_ylabel('Amplitude')
ax_e.legend(fontsize=4, loc='lower left')
ax_e.set_title(r"$A \cdot \cos(kr)$")
label_panel(ax_e, 'e')

# (f) sin lock-in product (raw)
ax_f = fig.add_subplot(gs[1, 1])
ax_f.plot(x, prod_sin, color=uncorr_color, lw=0.5, alpha=0.6, label=r'$A(r) \cdot \sin(kr)$')
ax_f.plot(x, -0.5 * np.sin(theta_fn(x)), 'k--', lw=1, alpha=0.7,
          label=r'$-\frac{1}{2}\sin(\theta)$ (slow)')
ax_f.set_xlim(*xlim_signal)
ax_f.set_xlabel(XLABEL_POS)
ax_f.legend(fontsize=4, loc='lower left')
ax_f.set_title(r"$A \cdot \sin(kr)$")
label_panel(ax_f, 'f')

# (g) Filtered cos → X(r)
ax_g = fig.add_subplot(gs[1, 2])
ax_g.plot(x, prod_cos, color=uncorr_color, alpha=0.2, lw=0.4, label='Raw product')
ax_g.plot(x, X_r, color=uncorr_color, lw=1.2, label=r'$X(r)$ = LPF[$A \cdot \cos$]')
ax_g.plot(x, 0.5 * np.cos(theta_fn(x)), 'k--', lw=0.8, alpha=0.5,
          label=r'True $\frac{1}{2}\cos(\theta)$')
ax_g.set_xlim(*xlim_signal)
ax_g.set_xlabel(XLABEL_POS)
ax_g.legend(fontsize=4)
ax_g.set_title("LPF → $X(r)$")
label_panel(ax_g, 'g')

# (h) Filtered sin → Y(r)
ax_h = fig.add_subplot(gs[1, 3])
ax_h.plot(x, prod_sin, color=uncorr_color, alpha=0.2, lw=0.4, label='Raw product')
ax_h.plot(x, Y_r, color=uncorr_color, lw=1.2, label=r'$Y(r)$ = LPF[$A \cdot \sin$]')
ax_h.plot(x, -0.5 * np.sin(theta_fn(x)), 'k--', lw=0.8, alpha=0.5,
          label=r'True $-\frac{1}{2}\sin(\theta)$')
ax_h.set_xlim(*xlim_signal)
ax_h.set_xlabel(XLABEL_POS)
ax_h.legend(fontsize=4)
ax_h.set_title("LPF → $Y(r)$")
label_panel(ax_h, 'h')


# ── Row 3: Phase extraction, drift recovery, kernel reassignment ──

# (i) Extracted phase θ(r)
ax_i = fig.add_subplot(gs[2, 0])
ax_i.plot(x, theta_fn(x), color=ref_color, lw=1.5,
          label=r'True $\theta(r) = \ln(r+1)$')
ax_i.plot(x, theta_extracted, color=uncorr_color, ls='--', lw=1.2, label=r'Extracted $\theta(r)$')
ax_i.set_xlim(*xlim_signal)
ax_i.set_xlabel(XLABEL_POS)
ax_i.set_ylabel(r'$\theta(r)$ (rad)')
ax_i.legend(fontsize=5)
ax_i.set_title(r"Phase: $\theta = \arctan(-Y/X)$")
label_panel(ax_i, 'i')

# (j) Recovered drift field
ax_j = fig.add_subplot(gs[2, 1])
ax_j.plot(x, u_fn(x), color=ref_color, lw=1.5, label='True $u(r)$')
ax_j.plot(x, u_extracted, color=uncorr_color, ls='--', lw=1.2, label='Recovered $u(r)$')
ax_j.set_xlim(*xlim_signal)
ax_j.set_xlabel(XLABEL_POS)
ax_j.set_ylabel('$u(r)$ (nm)')
ax_j.legend(fontsize=5)
ax_j.set_title("Drift: $u = \\theta / k$")
label_panel(ax_j, 'j')

# (k) Off-grid resampling: the same measured value, two assigned coordinates.
# Dots are evaluations of the MODE, not the measured data (independent-review
# catch, 2026-08-09); the caption must say so.
#
# Drawn as STEMS (zero baseline + vertical line + dot), not bare dots on the
# curve. Bare dots read as "samples of a signal", which is the idiom (l)
# uses for the measured heights; since the (k)-bottom and (l)-top arrays are
# numerically identical in this single-mode toy, the two frames were
# indistinguishable. Stems read as "a discrete sequence of coefficients",
# which is what these are (2026-09-07, Socratic walk-through with Marcos).
ax_k_top, ax_k_bot = stacked_pair(gs[2, 2:4])
for ax, xs, ys, c in ((ax_k_top, x_n, y_kernel_grid, uncorr_color),
                      (ax_k_bot, x_corr, y_kernel_corr, corr_color)):
    ax.axhline(0, color='0.75', lw=0.5, zorder=1)
    ax.vlines(xs, 0, ys, color=c, lw=0.9, zorder=4)
    ax.plot(xs, ys, 'o', ms=3, color=c, mec='white', mew=0.3, zorder=5)
# One y-label for the pair, centred on the gap between the frames: at 7 pt
# the label is taller than a single frame, so per-frame copies collide.
ax_k_top.set_ylabel(r'Weight $\cos(qr)$')
ax_k_top.yaxis.set_label_coords(-0.06, -0.19)
ax_k_bot.set_xlabel(XLABEL_POS)
ax_k_top.set_title(r"Fourier weights at grid $r_n$ vs corrected $\tilde{r}_n = r_n + u(r_n)$")
label_panel(ax_k_top, 'k')

h_grid = Line2D([], [], marker='o', ls='none', ms=3, color=uncorr_color,
                mec='white', mew=0.3)
h_corr = Line2D([], [], marker='o', ls='none', ms=3, color=corr_color,
                mec='white', mew=0.3)
h_link = Line2D([], [], color=link_color, lw=0.55)
ax_k_top.legend([h_grid, h_corr, h_link],
                [r'Grid $r_n$', r'Corrected $\tilde{r}_n$', 'Same sample'],
                fontsize=5, loc='upper right', framealpha=0.85,
                borderpad=0.3, handletextpad=0.4, handlelength=1.2,
                labelspacing=0.25)

# Connector lines: same sample, reassigned coordinate. Data coords on both
# ends, so they survive any layout change.
for xg, yg, xc, yc in zip(x_n, y_kernel_grid, x_corr, y_kernel_corr):
    fig.add_artist(ConnectionPatch(
        xyA=(xg, yg), coordsA=ax_k_top.transData,
        xyB=(xc, yc), coordsB=ax_k_bot.transData,
        color=link_color, lw=0.55, alpha=0.85, zorder=2,
    ))


# ── Row 4: Return to the uniform grid, then the corrected result ──

# (l) The inverse transform is GLOBAL: no per-sample connectors, one bold
# arrow instead (deliberate contrast with (k)).
# The thin curve in (l) is the ideal lattice REFERENCE (grey, as in a, c, m),
# not the kernel of (k), which stays dark. Cold-read fix, 2026-09-07.
ax_l_top, ax_l_bot = stacked_pair(gs[3, 0:2], curve_color=ref_color)
ax_l_top.plot(x_corr, y_reg, 'o', ms=3, color=corr_color,
              mec='white', mew=0.3, zorder=5)
ax_l_bot.plot(x_n, y_out, 'D', ms=3, mfc='white', mec=corr_color,
              mew=0.8, zorder=5)
ax_l_top.set_ylabel('Height')
ax_l_bot.set_ylabel('Height')
ax_l_bot.set_xlabel(XLABEL_POS)
ax_l_top.set_title("Back on the uniform grid")
label_panel(ax_l_top, 'l')

h_reg = Line2D([], [], marker='o', ls='none', ms=3, color=corr_color,
               mec='white', mew=0.3)
h_out = Line2D([], [], marker='D', ls='none', ms=3, mfc='white',
               mec=corr_color, mew=0.8)
h_ideal = Line2D([], [], color=ref_color, lw=0.8)
ax_l_top.legend([h_reg, h_ideal], [r'Measured $y_n$ at $\tilde{r}_n$', 'Ideal lattice'],
                fontsize=5, loc='upper right', framealpha=0.85,
                borderpad=0.3, handletextpad=0.4, handlelength=1.2)
ax_l_bot.legend([h_out], [r'Recomputed $\tilde{y}_n$ at grid $r_n$'],
                fontsize=5, loc='lower right', framealpha=0.85,
                borderpad=0.3, handletextpad=0.4, handlelength=1.2)

# Single bold arrow spanning the gap between the two frames of (l). Axes
# fractions, so it tracks the axes wherever constrained_layout puts them.
# The arrow carries BOTH steps that happen between the frames: the forward
# sum over the registered samples, then the ordinary inverse transform.
# Was labelled 'inverse FFT' only, which a cold read flagged as incomplete
# (2026-09-07). Arrow moved left to make room for the two-line label.
# One line only: the inter-frame gap is ~14 pt and the top frame's tick
# marks use 4 of them, so a two-line label (tried) collides with both frames.
_x_arrow = 0.50
fig.add_artist(ConnectionPatch(
    xyA=(_x_arrow, -0.03), coordsA='axes fraction', axesA=ax_l_top,
    xyB=(_x_arrow, 1.03), coordsB='axes fraction', axesB=ax_l_bot,
    arrowstyle='-|>', color='0.15', lw=1.1,
    shrinkA=0, shrinkB=0, mutation_scale=7, zorder=6,
))
ax_l_top.text(_x_arrow + 0.015, -0.23,
              r'$\tilde{x}_q=\Sigma_n\, y_n e^{-iq\tilde{r}_n}$, then $\tilde{y}=F^{-1}\tilde{x}$',
              transform=ax_l_top.transAxes, fontsize=5, color='0.15',
              ha='left', va='center', zorder=6)

# (m) Corrected signal  [old panel (k)]
ax_m = fig.add_subplot(gs[3, 2])
ax_m.plot(x, A_corrected, color=corr_color, lw=0.8, label='Corrected')
